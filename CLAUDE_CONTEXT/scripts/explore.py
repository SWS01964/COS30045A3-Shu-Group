import pandas as pd, sys
pd.set_option('display.width',220); pd.set_option('display.max_columns',30)
df = pd.read_pickle(sys.argv[1]).fillna({'Count of cases':0,'Died_cases':0,'Died_bed_days':0})
t = df[df['Cause of injury']=='Traffic']
print('Traffic per year (cases / hosp / bed days / died / ALOS / died per 1000):')
y = t.groupby('Calendar year')[['Count of cases','Hospitalisations','Bed days','Died_cases']].sum()
y['ALOS']=(y['Bed days']/y['Count of cases']).round(2); y['died_per_1000']=(1000*y['Died_cases']/y['Count of cases']).round(2)
print(y)
print('\nShare of all-cause injury (S00-T98 excl. medical) that is Traffic, 2021:')
inj = df[df['Cause of injury']!='Medical events'].groupby(['Calendar year','Cause of injury'])['Count of cases'].sum().unstack()
print((inj.div(inj.sum(axis=1),axis=0)*100).round(1))
print('\nRoad user: 2011 vs 2021 cases, % change, ALOS, died per 1000 (all years)')
ru = t.groupby(['Road user','Calendar year'])['Count of cases'].sum().unstack()
s = t.groupby('Road user')[['Count of cases','Bed days','Died_cases']].sum()
out = pd.DataFrame({'2011':ru[2011],'2019':ru[2019],'2021':ru[2021],'chg11_21%':((ru[2021]/ru[2011]-1)*100).round(1),
   'ALOS':(s['Bed days']/s['Count of cases']).round(2),'died/1000':(1000*s['Died_cases']/s['Count of cases']).round(2),'total':s['Count of cases'],'beddays':s['Bed days']})
print(out.sort_values('total',ascending=False))
print('\nSex x road user share male %, all years')
sx = t.groupby(['Road user','Sex'])['Count of cases'].sum().unstack().fillna(0)
print((100*sx['Male']/sx.sum(axis=1)).round(1).sort_values())
print('\nAge: ALOS and died/1000 all years')
a = t.groupby('Age group')[['Count of cases','Bed days','Died_cases']].sum()
a['ALOS']=(a['Bed days']/a['Count of cases']).round(2); a['died/1000']=(1000*a['Died_cases']/a['Count of cases']).round(2); print(a)
print('\nRemoteness: ALOS and died/1000 all years')
r = t.groupby('ABS remoteness area')[['Count of cases','Bed days','Died_cases']].sum()
r['ALOS']=(r['Bed days']/r['Count of cases']).round(2); r['died/1000']=(1000*r['Died_cases']/r['Count of cases']).round(2); print(r)
print('\nRemoteness x road user share % (all years)')
rr = t.groupby(['ABS remoteness area','Road user'])['Count of cases'].sum().unstack()
print((rr.div(rr.sum(axis=1),axis=0)*100).round(1).T)
print('\nCounterparty all years: cases, ALOS, died/1000')
c = t.groupby('Counterparty')[['Count of cases','Bed days','Died_cases']].sum()
c['ALOS']=(c['Bed days']/c['Count of cases']).round(2); c['died/1000']=(1000*c['Died_cases']/c['Count of cases']).round(2); print(c.sort_values('Count of cases',ascending=False))
print('\nMonth x year (traffic cases)')
order=['January','February','March','April','May','June','July','August','September','October','November','December']
m = t.groupby(['Calendar year','Month'])['Count of cases'].sum().unstack()[order]; print(m)
print('\nPedal cyclist by month 2019 vs 2020'); pc=t[t['Road user']=='Pedal cyclist'].groupby(['Calendar year','Month'])['Count of cases'].sum().unstack()[order]; print(pc.loc[[2019,2020,2021]])
print('\nAge x road user 2011 vs 2021 (selected)')
ar = t.groupby(['Road user','Age group','Calendar year'])['Count of cases'].sum().unstack()
for ruser in ['Pedal cyclist','Motorcyclist','Pedestrian','Car driver']:
    print(ruser); x=ar.loc[ruser][[2011,2016,2021]]; x['chg%']=((x[2021]/x[2011]-1)*100).round(1); print(x)
